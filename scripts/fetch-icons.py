#!/usr/bin/env python3
"""
Download the Tabler icons the bar draws and regenerate Icons.js. The panel types
Nerd Font glyphs instead (Model.GLYPHS).

The bar draws them as QtQuick.Shapes strokes from the SVG path data, so they take
the theme's colors and never depend on which glyphs the theme's Nerd Font build
carries. Run from the repo root:

    python3 scripts/fetch-icons.py
"""

import json
import os
import re
import urllib.request

VERSION = "3.47.0"
BASE = "https://cdn.jsdelivr.net/npm/@tabler/icons@%s/icons/%%s/%%s.svg" % VERSION

ICONS = [
    "mouse",
    "keyboard",
    "headphones",
    "headset",
    "device-airpods",
    "device-airpods-case",
    "device-gamepad-2",
    "device-mobile",
    "device-tablet",
    "device-speaker",
    "ballpen",
    "device-laptop",
    "device-remote",
    "music",
    "hand-finger",
    "battery-automotive",
    "battery",
    "plug-connected",
    "bolt",
    "clock-hour-4",
    "bluetooth",
]

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")


def fetch(name, out):
    with urllib.request.urlopen(BASE % ("outline", name), timeout=20) as r:
        svg = r.read().decode()
    with open(os.path.join(out, name + ".svg"), "w") as f:
        f.write(svg)
    # Every Tabler icon opens with an invisible 24x24 bounding path
    # (stroke="none"); the rest are the strokes.
    ds = [m.group(2) for m in re.finditer(r'<path(\s+stroke="none")?\s+d="([^"]+)"', svg) if not m.group(1)]
    if not ds or re.search(r"<(circle|rect|line|polyline|ellipse)\b", svg):
        raise SystemExit("%s: expected only <path> elements" % name)
    print("fetched", name)
    return " ".join(ds)


def main():
    paths = {name: fetch(name, os.path.join(ROOT, "icons")) for name in ICONS}

    lines = [
        ".pragma library",
        "",
        "// Generated by scripts/fetch-icons.py from Tabler Icons %s (MIT," % VERSION,
        "// https://tabler.io/icons). 24x24 viewBox, outlines in 2px round strokes.",
        "",
        "var paths = {",
    ]
    lines += ["  %s: %s," % (json.dumps(k), json.dumps(v)) for k, v in paths.items()]
    lines[-1] = lines[-1].rstrip(",")
    lines += ["}", ""]
    with open(os.path.join(ROOT, "Icons.js"), "w") as f:
        f.write("\n".join(lines))
    print("wrote Icons.js with %d icons" % len(paths))


if __name__ == "__main__":
    main()
