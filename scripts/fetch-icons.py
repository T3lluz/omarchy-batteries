#!/usr/bin/env python3
"""
Download the Tabler icons this plugin draws and regenerate Icons.js: outline
icons for the bar and the panel's details, filled ones for the panel's devices.

The bar and panel draw icons as QtQuick.Shapes strokes from the SVG path data,
so they take the theme's colors and never depend on which glyphs the theme's
Nerd Font build carries. Run from the repo root:

    python3 scripts/fetch-icons.py
"""

import json
import os
import re
import urllib.request

VERSION = "3.47.0"
BASE = "https://cdn.jsdelivr.net/npm/@tabler/icons@%s/icons/%%s/%%s.svg" % VERSION

ICONS = [
    # devices
    "mouse", "keyboard", "headphones", "headset", "device-airpods",
    "device-airpods-case", "device-gamepad-2", "device-mobile", "device-tablet",
    "device-watch", "device-speaker", "ballpen", "device-laptop", "device-desktop",
    "device-remote", "music", "hand-finger", "battery-automotive", "brand-apple",
    # battery levels
    "battery", "battery-1", "battery-2", "battery-3", "battery-4",
    "battery-charging", "battery-off", "battery-eco",
    # details
    "plug", "plug-connected", "bolt", "clock-hour-4", "heartbeat", "repeat",
    "gauge", "usb", "antenna-bars-5", "bluetooth", "zzz", "ear",
    # section headers
    "layout-navbar", "chart-line", "bell", "lock-open", "percentage", "devices",
    # updates and banners
    "refresh", "check", "alert-triangle",
]

# The panel draws devices solid (scripts/draw-glyphs.py). Kinds without a
# drawing there fall back to Tabler's filled icon, or its outline where
# Tabler has no filled one.
FILLED = ["device-remote", "ballpen", "battery-automotive"]

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")


def fetch(style, name, out):
    with urllib.request.urlopen(BASE % (style, name), timeout=20) as r:
        svg = r.read().decode()
    with open(os.path.join(out, name + ".svg"), "w") as f:
        f.write(svg)
    # Every Tabler icon opens with an invisible 24x24 bounding path
    # (stroke="none"); the rest are the strokes, or the fills.
    ds = [m.group(2) for m in re.finditer(r'<path(\s+stroke="none")?\s+d="([^"]+)"', svg) if not m.group(1)]
    if not ds or re.search(r"<(circle|rect|line|polyline|ellipse)\b", svg):
        raise SystemExit("%s/%s: expected only <path> elements" % (style, name))
    print("fetched", style, name)
    return " ".join(ds)


def main():
    os.makedirs(os.path.join(ROOT, "icons", "filled"), exist_ok=True)
    paths = {name: fetch("outline", name, os.path.join(ROOT, "icons")) for name in ICONS}
    filled = {name: fetch("filled", name, os.path.join(ROOT, "icons", "filled")) for name in FILLED}

    lines = [
        ".pragma library",
        "",
        "// Generated by scripts/fetch-icons.py from Tabler Icons %s (MIT," % VERSION,
        "// https://tabler.io/icons). 24x24 viewBox. `paths` are outlines in 2px",
        "// round strokes, `filled` are solid shapes filled non-zero.",
        "",
    ]
    for var, icons in (("paths", paths), ("filled", filled)):
        lines += ["var %s = {" % var]
        lines += ["  %s: %s," % (json.dumps(k), json.dumps(v)) for k, v in icons.items()]
        lines[-1] = lines[-1].rstrip(",")
        lines += ["}", ""]
    with open(os.path.join(ROOT, "Icons.js"), "w") as f:
        f.write("\n".join(lines))
    print("wrote Icons.js with %d outline and %d filled icons" % (len(paths), len(filled)))


if __name__ == "__main__":
    main()
